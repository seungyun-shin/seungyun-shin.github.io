export function npsLimitsOn(dateStr) {
  const d = dateStr || RATES.checkedOn;
  return d >= '2026-07-01' ? RATES.nps.baseLimits[1] : RATES.nps.baseLimits[0];
}

/** 화면 표시에 쓰는 평탄화 목록 (요율표 페이지) */
export function flattenRates(obj = RATES, prefix = '') {
  const out = [];
  for (const [k, v] of Object.entries(obj)) {
    if (v && typeof v === 'object' && 'confidence' in v && 'value' in v) out.push({ key: prefix + k, ...v });
    else if (Array.isArray(v)) v.forEach((x, i) => { if (x && x.confidence) out.push({ key: `${prefix}${k}[${i}]`, ...x }); });
    else if (v && typeof v === 'object') out.push(...flattenRates(v, `${prefix}${k}.`));
  }
  return out;
}
